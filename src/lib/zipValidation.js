export const validateZip = (countryCode, zip) => {
  const entry = ZIP_PATTERNS[countryCode];
  const value = (zip || '').trim();
  if (!entry || !value) return { valid: true, example: '' };
  const valid = entry.patterns.some((p) => {
    try { return new RegExp(p).test(value); } catch { return true; }
  });
  return { valid, example: entry.example };
};
